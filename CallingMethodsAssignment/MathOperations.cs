using System;

namespace CallingMethodsAssignment
{
    // This class contains methods that perform mathematical operations.
    internal class MathOperations
    {
        // This method adds 10 to the number entered by the user.
        public int AddTen(int number)
        {
            return number + 10;
        }

        // This method multiplies the number by 2.
        public int MultiplyByTwo(int number)
        {
            return number * 2;
        }

        // This method subtracts 5 from the number.
        public int SubtractFive(int number)
        {
            return number - 5;
        }
    }
}
